'use client';

/**
 * Authenticator app (backend: twofactor/). When on, signing in asks for the
 * app's code instead of sending one by SMS/email: safer against SIM swaps and
 * works without network signal.
 */

import { useEffect, useState } from 'react';
import { Alert, Box, Button, Chip, Stack, TextField, Typography } from '@mui/material';
import toast from 'react-hot-toast';
import { createAxiosClient } from '@/utils/clientFetch';
import { apiError } from '@/libs/seller-ops';

export default function TwoFactorSettings() {
  const [status, setStatus] = useState(null);
  const [setup, setSetup] = useState(null);       // {secret, qr_svg}
  const [codes, setCodes] = useState(null);
  const [code, setCode] = useState('');
  const [disabling, setDisabling] = useState(false);
  const [busy, setBusy] = useState(false);

  const load = () => createAxiosClient().get('/api/v1/2fa/').then(({ data }) => setStatus(data)).catch(() => {});
  useEffect(() => { load(); }, []);

  const post = async (body) => {
    setBusy(true);
    try {
      const { data } = await createAxiosClient().post('/api/v1/2fa/', body);
      return data;
    } catch (err) {
      toast.error(apiError(err, 'Something went wrong.'));
      return null;
    } finally {
      setBusy(false);
    }
  };

  if (!status) return null;

  return (
    <Box sx={{ border: 1, borderColor: 'divider', borderRadius: 2, p: 2.5, mb: 3 }}>
      <Stack direction="row" alignItems="center" spacing={1} sx={{ mb: 1 }}>
        <Typography sx={{ fontWeight: 700 }}>Authenticator app</Typography>
        {status.enabled ? <Chip size="small" color="success" label="On" /> : <Chip size="small" label="Off" />}
      </Stack>
      <Typography variant="body2" color="text.secondary" sx={{ mb: 2 }}>
        Sign in with a code from an app like Google Authenticator or Microsoft Authenticator instead of an SMS or
        email code. Safer if someone gets hold of your SIM or inbox.
      </Typography>

      {codes && (
        <Alert severity="warning" sx={{ mb: 2 }}>
          Save these recovery codes somewhere safe. Each one signs you in once if you lose your phone. They won&apos;t be
          shown again.
          <Box component="pre" sx={{ mt: 1, fontSize: 15, userSelect: 'all' }}>{codes.join('\n')}</Box>
        </Alert>
      )}

      {!status.enabled && !setup && (
        <Button variant="contained" disableElevation disabled={busy}
                onClick={async () => { const d = await post({ action: 'setup' }); if (d) setSetup(d); }}>
          Set up
        </Button>
      )}

      {!status.enabled && setup && (
        <Stack spacing={1.5} sx={{ maxWidth: 360 }}>
          <Typography variant="body2">1. Scan this with your authenticator app:</Typography>
          {/* SVG generated by the backend from the otpauth URI (no user content). */}
          <Box sx={{ width: 200, '& svg': { width: '100%', height: 'auto' } }} dangerouslySetInnerHTML={{ __html: setup.qr_svg }} />
          <Typography variant="caption" color="text.secondary">
            Can&apos;t scan? Enter this key: <b style={{ userSelect: 'all' }}>{setup.secret}</b>
          </Typography>
          <Typography variant="body2">2. Enter the 6-digit code it shows:</Typography>
          <TextField size="small" value={code} onChange={(e) => setCode(e.target.value.replace(/\D/g, '').slice(0, 6))}
                     inputProps={{ inputMode: 'numeric', autoComplete: 'one-time-code' }} />
          <Button variant="contained" disableElevation disabled={busy || code.length !== 6}
                  onClick={async () => {
                    const d = await post({ action: 'confirm', code });
                    if (d) { setCodes(d.recovery_codes); setSetup(null); setCode(''); load(); toast.success('Authenticator turned on'); }
                  }}>
            Turn on
          </Button>
        </Stack>
      )}

      {status.enabled && (
        <Stack spacing={1} sx={{ maxWidth: 360 }}>
          <Typography variant="body2" color="text.secondary">{status.recovery_codes_left} recovery codes left.</Typography>
          {!disabling ? (
            <Box><Button color="error" onClick={() => setDisabling(true)}>Turn off</Button></Box>
          ) : (
            <>
              <TextField size="small" label="Code from your app or a recovery code" value={code}
                         onChange={(e) => setCode(e.target.value.slice(0, 9))} />
              <Stack direction="row" spacing={1}>
                <Button color="error" variant="outlined" disabled={busy || code.length < 6}
                        onClick={async () => {
                          const d = await post({ action: 'disable', code });
                          if (d) { setDisabling(false); setCode(''); setCodes(null); load(); toast.success('Authenticator turned off'); }
                        }}>
                  Turn off
                </Button>
                <Button onClick={() => { setDisabling(false); setCode(''); }}>Cancel</Button>
              </Stack>
            </>
          )}
        </Stack>
      )}
    </Box>
  );
}
